import { useEffect, useRef, useState } from 'react'
import { Link, useNavigate, useSearchParams } from 'react-router-dom'
import { BookOpenText, FileText, Info, Lightbulb, MessageSquarePlus, Send, Sparkles, Trash2 } from 'lucide-react'
import { useAction, useDb } from '@/app/hooks'
import { useSession } from '@/app/session'
import type { AssistantMessage } from '@/domain/types'
import { formatRelative } from '@/lib/dates'
import { cn } from '@/lib/utils'
import { ask, assistantMode, clearHistory, deleteConversation, myConversations } from '@/services/assistant'
import { Button } from '@/components/ui/Button'
import { ConfirmDialog } from '@/components/ui/ConfirmDialog'
import { Textarea } from '@/components/ui/Form'
import { PageHeader } from '@/components/ui/Layout'

const STARTERS_HR = [
  'Which onboarding tasks are overdue?',
  'Show me requests awaiting my approval',
  'Summarize the unresolved HR service requests',
  'What should I follow up on today?',
]
const STARTERS = [
  'What is our annual leave policy?',
  'How do I request a workplace equipment replacement?',
  'How many days of leave do I have left?',
  'Do I need a medical certificate for sick leave?',
]

function Answer({ m, onAction }: { m: AssistantMessage; onAction: (a: AssistantMessage['actions'][number]) => void }) {
  return (
    <div className="min-w-0 flex-1 space-y-3">
      <p className="text-ink text-sm leading-relaxed whitespace-pre-line">{m.text}</p>
      {m.citations.length > 0 && (
        <div>
          <p className="text-muted mb-1 text-[11px] font-semibold tracking-wide uppercase">Sources</p>
          <ul className="flex flex-wrap gap-1.5">
            {m.citations.map((c, i) => (
              <li key={i}>
                <Link
                  to={c.href}
                  className="border-line hover:border-brand-600 bg-surface inline-flex max-w-full items-center gap-1.5 rounded-md border px-2 py-1 text-xs"
                >
                  {c.kind === 'policy' ? <BookOpenText size={12} aria-hidden /> : <FileText size={12} aria-hidden />}
                  <span className="truncate">{c.label}</span>
                  <span className="text-muted shrink-0">{c.detail}</span>
                </Link>
              </li>
            ))}
          </ul>
        </div>
      )}
      {m.suggestions.length > 0 && (
        <div className="bg-lavender/60 rounded-md px-3 py-2">
          <p className="text-ai mb-0.5 flex items-center gap-1 text-[11px] font-semibold tracking-wide uppercase">
            <Lightbulb size={12} aria-hidden /> Suggestion — not a fact or a decision
          </p>
          <ul className="text-ink-soft list-disc pl-4 text-sm">
            {m.suggestions.map((s) => (
              <li key={s}>{s}</li>
            ))}
          </ul>
        </div>
      )}
      {m.actions.length > 0 && (
        <div className="flex flex-wrap gap-2">
          {m.actions.map((a) => (
            <Button key={a.href} size="sm" onClick={() => onAction(a)}>
              {a.label}
            </Button>
          ))}
        </div>
      )}
      <p className="text-muted text-[11px]">
        {m.source === 'ai'
          ? 'Generated by the configured AI provider from records you can access. Check important details at the source.'
          : 'Demo mode: rule-based retrieval over your authorized data — not an AI model.'}
      </p>
    </div>
  )
}

export default function AssistantPage() {
  const db = useDb()
  const { account, can } = useSession()
  const navigate = useNavigate()
  const [params] = useSearchParams()
  const [conversationId, setConversationId] = useState<string | null>(null)
  const [text, setText] = useState(params.get('q') ?? '')
  const [pendingAction, setPendingAction] = useState<AssistantMessage['actions'][number] | null>(null)
  const [clearing, setClearing] = useState(false)
  const endRef = useRef<HTMLDivElement>(null)
  const conversations = myConversations(account)
  const convo = conversations.find((c) => c.id === conversationId)
  const send = useAction((q: string) => ask(account, conversationId, q))
  const starters = can('requests.handle') || account.role === 'manager' ? [...STARTERS_HR.slice(0, 3), STARTERS[0] as string] : STARTERS

  useEffect(() => {
    endRef.current?.scrollIntoView({ block: 'end' })
  }, [convo?.messages.length])

  const submit = async (q: string) => {
    if (!q.trim()) return
    setText('')
    const r = await send.run(q)
    if (r.ok) setConversationId(r.value)
    else setText(q)
  }
  const onAction = (a: AssistantMessage['actions'][number]) => (a.requiresConfirmation ? setPendingAction(a) : navigate(a.href))

  return (
    <div>
      <PageHeader
        title="AI Assistant"
        description="Ask about company policies and the HR work you’re allowed to see. Answers link to their sources."
        actions={
          <span
            className={cn(
              'inline-flex items-center gap-1.5 rounded-md px-2.5 py-1.5 text-xs font-medium',
              assistantMode === 'ai' ? 'bg-lavender text-ai' : 'bg-warning-soft text-warning',
            )}
          >
            <Info size={13} aria-hidden />
            {assistantMode === 'ai' ? 'Connected to AI service (server-side)' : 'Demo mode — rule-based retrieval, not AI'}
          </span>
        }
      />
      <div className="grid grid-cols-1 gap-5 lg:grid-cols-[16rem_minmax(0,1fr)]">
        <aside className="border-line bg-surface shadow-card h-fit rounded-lg border lg:sticky lg:top-20">
          <div className="border-line flex items-center gap-2 border-b p-2">
            <Button size="sm" className="flex-1" icon={MessageSquarePlus} onClick={() => setConversationId(null)}>
              New conversation
            </Button>
            {conversations.length > 0 && (
              <Button size="sm" variant="ghost" iconOnly icon={Trash2} aria-label="Clear all history" onClick={() => setClearing(true)} />
            )}
          </div>
          <ul className="max-h-[50vh] overflow-y-auto p-1.5">
            {conversations.length === 0 && <li className="text-muted px-2 py-3 text-xs">Your conversations are private to you.</li>}
            {conversations.map((c) => (
              <li key={c.id} className="group flex items-center">
                <button
                  type="button"
                  onClick={() => setConversationId(c.id)}
                  className={cn(
                    'min-w-0 flex-1 rounded-md px-2 py-1.5 text-left text-sm',
                    c.id === conversationId ? 'bg-brand-50 text-brand-800' : 'hover:bg-page',
                  )}
                >
                  <span className="block truncate">{c.title}</span>
                  <span className="text-muted block text-[11px]">{formatRelative(c.updatedAt)}</span>
                </button>
                <button
                  type="button"
                  className="text-muted hover:text-danger rounded p-1 opacity-0 group-hover:opacity-100 focus:opacity-100"
                  aria-label={`Delete conversation ${c.title}`}
                  onClick={() => {
                    deleteConversation(account, c.id)
                    if (c.id === conversationId) setConversationId(null)
                  }}
                >
                  <Trash2 size={13} />
                </button>
              </li>
            ))}
          </ul>
        </aside>
        <section aria-label="Conversation" className="border-line bg-surface shadow-card flex min-h-[60vh] flex-col rounded-lg border">
          <div className="flex-1 space-y-6 overflow-y-auto px-4 py-5 sm:px-6" aria-live="polite">
            {!convo ? (
              <div className="mx-auto max-w-lg pt-6 text-center">
                <span className="bg-lavender text-ai mx-auto grid size-11 place-items-center rounded-full">
                  <Sparkles size={20} aria-hidden />
                </span>
                <p className="mt-3 font-medium">How can I help, {account.name.split(' ')[0]}?</p>
                <p className="text-muted mt-1 text-sm">
                  I only use policies and records you’re authorized to see, and I’ll tell you when I can’t find an answer. I never approve, reject or decide
                  anything for you.
                </p>
                <div className="mt-5 grid gap-2 sm:grid-cols-2">
                  {starters.map((s) => (
                    <button
                      key={s}
                      type="button"
                      onClick={() => void submit(s)}
                      className="border-line hover:border-brand-600 rounded-md border px-3 py-2 text-left text-sm"
                    >
                      {s}
                    </button>
                  ))}
                </div>
              </div>
            ) : (
              convo.messages.map((m) =>
                m.role === 'user' ? (
                  <div key={m.id} className="flex justify-end">
                    <p className="bg-brand-600 max-w-[85%] rounded-lg rounded-br-sm px-3.5 py-2 text-sm whitespace-pre-line text-white">{m.text}</p>
                  </div>
                ) : (
                  <div key={m.id} className="flex gap-3">
                    <span className="bg-lavender text-ai grid size-7 shrink-0 place-items-center rounded-full">
                      <Sparkles size={14} aria-hidden />
                    </span>
                    <Answer m={m} onAction={onAction} />
                  </div>
                ),
              )
            )}
            {send.pending && (
              <p className="text-muted text-sm" role="status">
                Looking that up…
              </p>
            )}
            <div ref={endRef} />
          </div>
          <form
            className="border-line flex items-end gap-2 border-t p-3"
            onSubmit={(e) => {
              e.preventDefault()
              void submit(text)
            }}
          >
            <Textarea
              aria-label="Your question"
              rows={2}
              maxLength={1000}
              value={text}
              onChange={(e) => setText(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === 'Enter' && !e.shiftKey) {
                  e.preventDefault()
                  void submit(text)
                }
              }}
              placeholder="Ask about a policy, your requests, approvals or today’s priorities…"
              className="min-h-[44px] resize-none"
            />
            <Button type="submit" variant="primary" icon={Send} disabled={!text.trim()} loading={send.pending}>
              Ask
            </Button>
          </form>
        </section>
      </div>
      <ConfirmDialog
        open={Boolean(pendingAction)}
        onClose={() => setPendingAction(null)}
        title={pendingAction?.label ?? ''}
        description="This opens the form so you can review the details. Nothing is submitted until you send it there."
        confirmLabel="Open form"
        onConfirm={() => {
          if (pendingAction) navigate(pendingAction.href)
          setPendingAction(null)
        }}
      />
      <ConfirmDialog
        open={clearing}
        onClose={() => setClearing(false)}
        title="Clear your conversation history?"
        description="Deletes all your assistant conversations. Nobody else can see them."
        tone="danger"
        confirmLabel="Clear history"
        onConfirm={() => {
          clearHistory(account)
          setConversationId(null)
          setClearing(false)
        }}
      />
      {db.policies.length === 0 && <p className="text-muted mt-3 text-xs">No policies are published yet, so policy questions cannot be answered.</p>}
    </div>
  )
}
